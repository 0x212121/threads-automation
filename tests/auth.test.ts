import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import session from 'express-session';
import request from 'supertest';
import type { Pool } from 'pg';
import { createApp } from '../src/app.js';
import { bootstrapAdmin, INITIAL_ADMIN_EMAIL } from '../src/bootstrap-admin.js';

test('sesi lokal memerlukan CSRF, merotasi sesi, dan menolak pengguna nonaktif', async () => {
  const db = new PGlite();
  await db.exec(await readFile('db/migrations/002_local_identity.sql', 'utf8'));
  await db.exec(await readFile('db/migrations/006_password_reset.sql', 'utf8'));
  const query = async (text: string, params?: unknown[]) => { const result = await db.query(text, params); return { ...result, rowCount: result.affectedRows ?? result.rows.length }; };
  const pool = { query, connect: async () => ({ query, release: () => {} }) } as unknown as Pool;
  await bootstrapAdmin(pool, 'kata sandi untuk pengujian');
  const origin = 'http://localhost:3000';
  const app = await createApp({ pool, store: new session.MemoryStore(), secret: 'a'.repeat(48), origin, secure: false, trustProxy: false });
  const agent = request.agent(app);
  assert.equal((await agent.get('/api/auth/me')).status, 401);
  const initial = await agent.get('/api/auth/csrf');
  const token = initial.body.csrfToken as string;
  const initialCookie = initial.headers['set-cookie']?.[0];
  assert.match(initialCookie ?? '', /SameSite=Lax/i);
  const blocked = await agent.post('/api/auth/login').set('Origin', 'http://situs-lain.test').set('X-CSRF-Token', token).send({ email: INITIAL_ADMIN_EMAIL, password: 'kata sandi untuk pengujian' });
  assert.equal(blocked.status, 403);
  const wrong = await agent.post('/api/auth/login').set('Origin', origin).set('X-CSRF-Token', token).send({ email: INITIAL_ADMIN_EMAIL, password: 'salah' });
  assert.equal(wrong.status, 401);
  const unknown = await agent.post('/api/auth/login').set('Origin', origin).set('X-CSRF-Token', token).send({ email: 'tidak-ada@example.test', password: 'salah' });
  assert.equal(unknown.status, 401);
  assert.deepEqual(unknown.body, wrong.body);
  const login = await agent.post('/api/auth/login').set('Origin', origin).set('X-CSRF-Token', token).send({ email: INITIAL_ADMIN_EMAIL, password: 'kata sandi untuk pengujian' });
  assert.equal(login.status, 200);
  assert.equal(login.body.user.emailVerified, false);
  assert.notEqual(login.body.csrfToken, token);
  assert.notEqual(login.headers['set-cookie']?.[0], initialCookie);
  assert.equal((await agent.get('/api/auth/me')).status, 200);
  assert.equal((await agent.post('/api/auth/logout').set('Origin', origin).set('X-CSRF-Token', token)).status, 403);
  assert.equal((await agent.post('/api/auth/logout').set('Origin', origin).set('X-CSRF-Token', login.body.csrfToken)).status, 204);
  assert.equal((await agent.get('/api/auth/me')).status, 401);
  const second = (await agent.get('/api/auth/csrf')).body.csrfToken as string;
  const relogin = await agent.post('/api/auth/login').set('Origin', origin).set('X-CSRF-Token', second).send({ email: INITIAL_ADMIN_EMAIL, password: 'kata sandi untuk pengujian' });
  assert.equal(relogin.status, 200);
  await db.query('UPDATE local_users SET disabled_at=now() WHERE email=$1', [INITIAL_ADMIN_EMAIL]);
  assert.equal((await agent.get('/api/auth/me')).status, 401);
  const third = (await agent.get('/api/auth/csrf')).body.csrfToken as string;
  assert.equal((await agent.post('/api/auth/login').set('Origin', origin).set('X-CSRF-Token', third).send({ email: INITIAL_ADMIN_EMAIL, password: 'kata sandi untuk pengujian' })).status, 401);
  for (let index = 0; index < 4; index++) await agent.post('/api/auth/login').set('Origin', origin).set('X-CSRF-Token', third).send({ email: INITIAL_ADMIN_EMAIL, password: 'salah' });
  assert.equal((await agent.post('/api/auth/login').set('Origin', origin).set('X-CSRF-Token', third).send({ email: INITIAL_ADMIN_EMAIL, password: 'salah' })).status, 429);
  await db.close();
});
