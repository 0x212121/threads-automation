import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import session from 'express-session';
import request from 'supertest';
import type { Pool } from 'pg';
import { createApp } from '../src/app.js';
import { hashPassword } from '../src/password.js';
import { TokenVault } from '../src/token-vault.js';
import { ThreadsAccounts } from '../src/threads-accounts.js';

test('anggota aktif dapat melihat draft tim dan membuat draft melalui sesi dengan CSRF', async () => {
  const db = new PGlite();
  for (const migration of ['001_content.sql', '002_local_identity.sql', '006_password_reset.sql', '007_threads_accounts.sql','013_token_refresh.sql', '009_publication_jobs.sql','011_publication_diagnostics.sql','012_media.sql','014_carousel.sql','015_thread_replies.sql','016_publication_reference_repairs.sql','017_publication_failure_details.sql','018_workspace_management.sql']) await db.exec(await readFile(`db/migrations/${migration}`, 'utf8'));
  const query = async (text: string, params?: unknown[]) => { const result = await db.query(text, params); return { ...result, rowCount: result.affectedRows ?? result.rows.length }; };
  const pool = { query, connect: async () => ({ query, release: () => {} }) } as unknown as Pool;
  const password = 'kata sandi untuk pengujian';
  const hash = await hashPassword(password);
  const first = '11111111-1111-4111-8111-111111111111', second = '22222222-2222-4222-8222-222222222222';
  const admin = '33333333-3333-4333-8333-333333333333';
  await db.query("INSERT INTO local_users (id,email,password_hash,role,email_verified_at) VALUES ($1,'satu@example.test',$2,'editor',now()),($3,'dua@example.test',$2,'reviewer',now()),($4,'admin@example.test',$2,'admin',now())", [first, hash, second, admin]);
  const accountId = await new ThreadsAccounts(pool, new TokenVault(Buffer.alloc(32, 5))).register(admin, { threadsUserId: '123456', username: 'akun-uji', token: 'token-uji-tidak-nyata', expiresAt: new Date(Date.now() + 86400000) });
  const origin = 'http://localhost:3000';
  const app = await createApp({ pool, store: new session.MemoryStore(), secret: 'a'.repeat(48), origin, secure: false, trustProxy: false });
  const anon = request.agent(app);
  assert.equal((await anon.get('/api/posts')).status, 401);
  assert.equal((await anon.get('/api/threads/accounts')).status, 401);
  const agent1 = request.agent(app);
  const t1 = (await agent1.get('/api/auth/csrf')).body.csrfToken;
  const login1 = await agent1.post('/api/auth/login').set('Origin', origin).set('X-CSRF-Token', t1).send({ email: 'satu@example.test', password });
  const csrf1 = login1.body.csrfToken;
  assert.equal((await agent1.post('/api/posts').set('Origin', origin).set('X-CSRF-Token', 'salah').send({ body: 'draft' })).status, 403);
  assert.equal((await agent1.post('/api/posts').set('Origin', origin).set('X-CSRF-Token', csrf1).send({ body: 'draft', destinationAccountId: first })).status, 400);
  const accounts = await agent1.get('/api/threads/accounts');
  assert.equal(accounts.body.accounts[0].username, 'akun-uji');
  assert.equal(JSON.stringify(accounts.body).includes('token-uji'), false);
  const created = await agent1.post('/api/posts').set('Origin', origin).set('X-CSRF-Token', csrf1).send({ body: 'Draft bersama', destinationAccountId: accountId });
  assert.equal(created.status, 201);
  const agent2 = request.agent(app);
  const t2 = (await agent2.get('/api/auth/csrf')).body.csrfToken;
  const login2 = await agent2.post('/api/auth/login').set('Origin', origin).set('X-CSRF-Token', t2).send({ email: 'dua@example.test', password });
  assert.equal(login2.status, 200);
  const csrf2 = login2.body.csrfToken;
  const list = await agent2.get('/api/posts');
  assert.equal(list.status, 200);
  assert.equal(list.body.posts[0].body, 'Draft bersama');
  assert.equal(list.body.posts[0].created_by, first);
  assert.equal(list.body.posts[0].destination_account_id, accountId);
  const id = created.body.post.id;
  assert.equal((await agent2.put(`/api/posts/${id}`).set('Origin', origin).set('X-CSRF-Token', csrf2).send({ body: 'ubah', revision: 1 })).status, 403);
  assert.equal((await agent2.post(`/api/posts/${id}/submit`).set('Origin', origin).set('X-CSRF-Token', csrf2).send({ revision: 1 })).status, 403);
  const submit = await agent1.post(`/api/posts/${id}/submit`).set('Origin', origin).set('X-CSRF-Token', csrf1).send({ revision: 1 });
  assert.equal(submit.status, 200);
  assert.equal((await agent1.post(`/api/posts/${id}/approve`).set('Origin', origin).set('X-CSRF-Token', csrf1).send({ revision: 2 })).status, 403);
  const approved = await agent2.post(`/api/posts/${id}/approve`).set('Origin', origin).set('X-CSRF-Token', csrf2).send({ revision: 2 });
  assert.equal(approved.status, 200);
  assert.equal(approved.body.post.status, 'approved');
  assert.equal((await agent1.put(`/api/posts/${id}`).set('Origin', origin).set('X-CSRF-Token', csrf1).send({ body: 'ubah', revision: 2 })).status, 409);
  const edited = await agent1.put(`/api/posts/${id}`).set('Origin', origin).set('X-CSRF-Token', csrf1).send({ body: 'ubah', revision: 3 });
  assert.equal(edited.status, 200);
  assert.equal(edited.body.post.status, 'draft');
  assert.equal((await agent1.get('/api/posts')).body.posts[0].destination_account_id, accountId);
  await db.query("UPDATE threads_accounts SET status='disconnected', encrypted_token=NULL, token_iv=NULL, token_tag=NULL WHERE id=$1", [accountId]);
  assert.equal((await agent1.post(`/api/posts/${id}/submit`).set('Origin', origin).set('X-CSRF-Token', csrf1).send({ revision: 4 })).status, 409);
  assert.equal((await agent1.put(`/api/posts/${id}`).set('Origin', origin).set('X-CSRF-Token', csrf1).send({ body: 'ubah', revision: 4, destinationAccountId: null })).status, 200);
  await db.query('UPDATE local_users SET disabled_at=now() WHERE id=$1', [second]);
  assert.equal((await agent2.get('/api/posts')).status, 401);
  await db.close();
});
