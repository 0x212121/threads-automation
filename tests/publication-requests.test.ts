import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import type { Pool } from 'pg';
import { PublicationRequests } from '../src/publication-requests.js';

test('jadwal hanya oleh pembuat, reviewer, atau admin dan perubahan waktu menjaga persetujuan', async () => {
  const db = new PGlite();
  for (const name of ['001_content.sql','002_local_identity.sql','007_threads_accounts.sql','013_token_refresh.sql','009_publication_jobs.sql','011_publication_diagnostics.sql','012_media.sql','014_carousel.sql','015_thread_replies.sql','016_publication_reference_repairs.sql','010_publication_resolutions.sql']) await db.exec(await readFile(`db/migrations/${name}`, 'utf8'));
  const query = async (text: string, params?: unknown[]) => { const result = await db.query(text, params); return { ...result, rowCount: result.rows.length }; };
  const pool = { connect: async () => ({ query, release: () => {} }) } as unknown as Pool;
  const owner='11111111-1111-4111-8111-111111111111', other='22222222-2222-4222-8222-222222222222', reviewer='33333333-3333-4333-8333-333333333333', account='44444444-4444-4444-8444-444444444444', post='55555555-5555-4555-8555-555555555555';
  await db.query("INSERT INTO local_users(id,email,password_hash,role,email_verified_at) VALUES ($1,'owner@example.test','x','editor',now()),($2,'other@example.test','x','editor',now()),($3,'reviewer@example.test','x','reviewer',now())", [owner,other,reviewer]);
  await db.query("INSERT INTO threads_accounts(id,threads_user_id,username,connected_by,encrypted_token,token_iv,token_tag,token_expires_at,status) VALUES ($1,'123','akun',$2,'x','x','x',now()+interval '10 days','active')", [account,reviewer]);
  await db.exec('BEGIN');
  await db.query("INSERT INTO content_posts(id,created_by,status,current_version) VALUES ($1,$2,'approved',1)", [post,owner]);
  await db.query("INSERT INTO content_versions(post_id,version,body,destination_account_id,created_by) VALUES ($1,1,'teks',$2,$3)", [post,account,owner]);
  await db.exec('COMMIT');
  await db.query("INSERT INTO content_reviews(id,post_id,content_version,reviewer_id,decision) VALUES ('66666666-6666-4666-8666-666666666666',$1,1,$2,'approved')", [post,reviewer]);
  const requests = new PublicationRequests(pool);
  const later = new Date(Date.now()+86400000).toISOString().slice(0,16);
  const laterAgain = new Date(Date.now()+172800000).toISOString().slice(0,16);
  await assert.rejects(requests.schedule(other,post,1,later,'UTC'), /akses/);
  const scheduled = await requests.schedule(owner,post,1,later,'UTC');
  await assert.rejects(requests.schedule(reviewer,post,1,later,'UTC'), /aktif/);
  const changed = await requests.change(reviewer,post,1,scheduled.id,'reschedule',laterAgain,'UTC');
  assert.equal(changed.status, 'scheduled');
  assert.equal((await db.query<{ status: string }>('SELECT status FROM content_posts WHERE id=$1', [post])).rows[0]?.status, 'approved');
  await db.query("UPDATE threads_accounts SET status='disconnected', encrypted_token=NULL, token_iv=NULL, token_tag=NULL WHERE id=$1", [account]);
  const cancelled = await requests.change(owner,post,1,scheduled.id,'cancel');
  assert.equal(cancelled.status, 'cancelled');
  const uncertain='77777777-7777-4777-8777-777777777777';
  await db.query("INSERT INTO publication_jobs(id,post_id,content_version,account_id,requested_by,scheduled_at,time_zone,next_attempt_at,status) VALUES ($1,$2,1,$3,$4,now(),'UTC',now(),'uncertain')", [uncertain,post,account,owner]);
  await assert.rejects(requests.resolveUncertain(other,post,1,uncertain,'not_published'), /akses/);
  const resolved = await requests.resolveUncertain(reviewer,post,1,uncertain,'published');
  assert.equal(resolved.status, 'confirmed_published');
  assert.equal((await db.query<{ decision: string }>('SELECT decision FROM publication_resolutions WHERE job_id=$1',[uncertain])).rows[0]?.decision, 'published');
  await assert.rejects(requests.resolveUncertain(reviewer,post,1,uncertain,'not_published'), /sudah ditangani/);
  await db.close();
});
