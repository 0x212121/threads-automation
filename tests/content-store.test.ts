import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import type { Pool } from 'pg';
import { ContentStore } from '../src/content-store.js';

test('konten, versi dan persetujuan tersimpan secara transaksional', async () => {
  const db = new PGlite();
  await db.exec(await readFile('db/migrations/001_content.sql', 'utf8'));
  await db.exec(await readFile('db/migrations/002_local_identity.sql', 'utf8'));
  await db.exec(await readFile('db/migrations/007_threads_accounts.sql', 'utf8'));
  await db.exec(await readFile('db/migrations/009_publication_jobs.sql', 'utf8'));
  await db.exec(await readFile('db/migrations/012_media.sql', 'utf8'));
  const client = { query: (text: string, params?: unknown[]) => db.query(text, params), release: () => {} };
  const pool = { connect: async () => client } as unknown as Pool;
  const store = new ContentStore(pool);
  const admin = { id: '11111111-1111-4111-8111-111111111111', role: 'admin' as const };
  const editor = { id: '22222222-2222-4222-8222-222222222222', role: 'editor' as const };
  let post = await store.create(admin, { body: 'Draft pertama', destinationAccountId: null });
  post = await store.transition(admin, post.id, post.revision, 'submit');
  await assert.rejects(store.transition(editor, post.id, post.revision, 'approve'));
  post = await store.transition(admin, post.id, post.revision, 'approve');
  assert.equal(post.status, 'approved');
  const previous = post.revision;
  post = await store.edit(admin, post.id, post.revision, { body: 'Konten diubah', destinationAccountId: null });
  assert.equal(post.status, 'draft');
  assert.equal(post.current_version, 2);
  await assert.rejects(store.transition(admin, post.id, previous, 'submit'), /muat ulang/);
  const versions = await db.query<{ body: string }>('SELECT body FROM content_versions WHERE post_id=$1 ORDER BY version', [post.id]);
  assert.deepEqual(versions.rows.map(row => row.body), ['Draft pertama', 'Konten diubah']);
  const reviews = await db.query<{ content_version: number }>('SELECT content_version FROM content_reviews WHERE post_id=$1', [post.id]);
  assert.equal(reviews.rows.length, 1);
  assert.equal(reviews.rows[0]?.content_version, 1);
  post = await store.transition(admin, post.id, post.revision, 'submit');
  post = await store.transition(admin, post.id, post.revision, 'reject');
  assert.equal(post.status, 'rejected');
  post = await store.transition(admin, post.id, post.revision, 'submit');
  assert.equal(post.status, 'submitted');
  const invalidReview = await db.query<{ count: string }>("SELECT count(*)::text AS count FROM content_reviews WHERE decision='approved' AND reviewer_id=$1", [editor.id]);
  assert.equal(invalidReview.rows[0]?.count, '0');
  await db.close();
});
